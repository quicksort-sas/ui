export type IconName = keyof typeof PIXELS
export const ICON_NAMES = Object.keys(PIXELS) as IconName[]

/** One path per colour, each run of pixels on a row drawn as a single rectangle. */
function toPath(rows: readonly string[], ch: "#" | "+") {
  let d = ""
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== ch) continue
      let w = 1
      while (row[x + w] === ch) w++
      d += `M${x} ${y}h${w}v1h-${w}z`
      x += w - 1
    }
  })
  return d
}

const PATHS = Object.fromEntries(
  ICON_NAMES.map((name) => [name, { ink: toPath(PIXELS[name], "#"), accent: toPath(PIXELS[name], "+") }])
) as Record<IconName, { ink: string; accent: string }>

type IconProps = Omit<React.ComponentProps<"svg">, "children"> & {
  name: IconName
  /** Rendered size in px. The grid is 16 × 16; use 20, 24 or 28. */
  size?: 20 | 24 | 28
  /** Draw the accent pixels in lime. Turn off when another lime element is already on the screen. */
  accent?: boolean
  /** Accessible name. Without it the icon is decorative (aria-hidden). */
  title?: string
}

function Icon({ name, size = 24, accent = true, title, className, ...props }: IconProps) {
  const { ink, accent: acc } = PATHS[name]
  return (
    <svg
      data-slot="icon"
      data-icon={name}
      viewBox="0 0 16 16"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      className={cn("inline-block shrink-0", className)}
      {...props}
    >
      {title && <title>{title}</title>}
      <path d={ink} fill="currentColor" />
      {acc && <path data-slot="icon-accent" d={acc} fill={accent ? "var(--pivot)" : "currentColor"} />}
    </svg>
  )
}

type NamedIconProps = Omit<IconProps, "name">
const named = (name: IconName) => {
  const C = (props: NamedIconProps) => <Icon name={name} {...props} />
  C.displayName = `${name[0].toUpperCase()}${name.slice(1)}Icon`
  return C
}

